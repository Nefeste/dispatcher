// Числа смены (docs/08-game-design.md, §9 — там они живут; здесь — их копия для движка, с той же единицей).
// Время движка — целые миллисекунды от начала смены.
const S = 1000;
const MIN = 60 * S;

/** Принять звонок, услышать адрес и повод. */
export const ANSWER = 30 * S;
/** Переспросить. */
export const AGAIN = 10 * S;
/** Решение и отправка бригады. */
export const DECIDE = 10 * S;
/** Повторный звонок — через столько ожидания на линии или без бригады. */
export const REPEAT: readonly [number, number] = [8 * MIN, 15 * MIN];
/** Передача в больнице. */
export const HANDOVER = 15 * MIN;
/** Сколько бригада ждёт ответа на доклад, прежде чем везти в больницу, которую предложила. */
export const REPORT_WAIT = 2 * MIN;
/** Норма доезда экстренной формы — от поступления вызова до прибытия бригады (388н, прил. 2, п. 6). */
export const NORM_EMERGENCY = 20 * MIN;
/** Цель для неотложной формы — правило игры (pgg2026, 543н: неотложная первичная помощь — не позже 2 часов). */
export const NORM_URGENT = 120 * MIN;
/** После отказа в выезде, когда повод был, звонят снова — через столько (срез, С3; §7 геймдизайна). Звонок не позже
 *  конца смены, а если смена уже кончается — не раньше чем через `CALLBACK_SOON`. */
export const CALLBACK: readonly [number, number] = [60 * MIN, 180 * MIN];
export const CALLBACK_SOON = 15 * MIN;
/** Укладка бригады — на столько вызовов (срез, часть С2; §15 геймдизайна). */
export const KIT = 4;
/** Пополнить пустую укладку на подстанции. */
export const RESTOCK = 20 * MIN;
