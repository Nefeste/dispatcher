// Числа смены (docs/08-game-design.md, §9 — там они живут; здесь — их копия для движка, с той же единицей).
// Время движка — целые миллисекунды от начала смены.
const S = 1000;
const MIN = 60 * S;

/** Принять звонок, услышать адрес и повод. */
export const ANSWER = 30 * S;
/** Переспросить. */
export const AGAIN = 10 * S;
/** Решение и отправка бригады. */
export const DECIDE = 10 * S;
/** Повторный звонок — через столько ожидания на линии или без бригады. */
export const REPEAT: readonly [number, number] = [8 * MIN, 15 * MIN];
/** Передача в больнице. */
export const HANDOVER = 15 * MIN;
/** Сколько бригада ждёт ответа на доклад, прежде чем везти в больницу, которую предложила. */
export const REPORT_WAIT = 2 * MIN;
/** Норма доезда экстренной формы — от поступления вызова до прибытия бригады (388н, прил. 2, п. 6). */
export const NORM_EMERGENCY = 20 * MIN;
/** Цель для неотложной формы — правило игры (pgg2026, 543н: неотложная первичная помощь — не позже 2 часов). */
export const NORM_URGENT = 120 * MIN;
/** После отказа в выезде, когда повод был, звонят снова — через столько (срез, С3; §7 геймдизайна). Звонок не позже
 *  конца смены, а если смена уже кончается — не раньше чем через `CALLBACK_SOON`. */
export const CALLBACK: readonly [number, number] = [60 * MIN, 180 * MIN];
export const CALLBACK_SOON = 15 * MIN;
/** Бригада на месте просит реанимационную через столько после прибытия и ждёт ответа столько (срез, С4; §5 и §9
 *  геймдизайна); не ответили — везёт сама. */
export const ASK_AFTER = 3 * MIN;
export const ASK_WAIT = 2 * MIN;
/** Укладка бригады — на столько вызовов (срез, часть С2; §15 геймдизайна). */
export const KIT = 4;
/** Пополнить пустую укладку на подстанции. */
export const RESTOCK = 20 * MIN;
// Бригада на месте просит решение не про медицину (срез, С4, вторая половина; решение владельца #34, вариант 2; §5 и §9
// геймдизайна). Слова и время, не медицинские факты: числа — правило игры, их подбирает «виртуальный диспетчер».
/** Перезвонить звонящему — узнать код домофона, уточнить адрес: минута диспетчера, мир идёт. */
export const SNAG_PHONE = 1 * MIN;
/** Доли вызовов, где бригада попросит решение (1/10 000); на вызов — не больше одной просьбы. Подъезд закрыт — только
 *  дома и только если диспетчер не спросил «Подъезд, этаж, код домофона?». */
export const DOOR_CHANCE = 2000;
export const ADDRESS_CHANCE = 600;
export const VICTIM_CHANCE = 500;
/** Ждать у подъезда, пока откроют сами. */
export const DOOR_WAIT: readonly [number, number] = [4 * MIN, 12 * MIN];
/** Адрес не тот: верный — в стольких минутах езды; искать самим — столько. */
export const ADDRESS_NEAR: readonly [number, number] = [1 * MIN, 4 * MIN];
export const ADDRESS_SEARCH: readonly [number, number] = [5 * MIN, 12 * MIN];
/** Второй пострадавший: бригада ко второму работает на месте столько; одна бригада задерживается на столько. */
export const VICTIM_SCENE: readonly [number, number] = [15 * MIN, 25 * MIN];
export const VICTIM_EXTRA: readonly [number, number] = [10 * MIN, 20 * MIN];
